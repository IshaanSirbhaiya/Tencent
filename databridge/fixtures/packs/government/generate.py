def clean(out: Path) -> None:
    """Remove only what this generator owns.

    Hand-written files -- the DDL, roles.yaml, SOURCES.md, ONTOLOGY_NOTES.md,
    the top-level README and this script -- are never touched.
    """
    for relative in GENERATED_DIRECTORIES:
        target = out / relative
        if target.exists():
            shutil.rmtree(target)
    for relative in GENERATED_ROOT_FILES:
        target = out / relative
        if target.exists():
            target.unlink()


def write_manifest(out: Path, seed: int, scale: float,
                   counts: dict[str, int], row_counts: dict[str, int],
                   extra: dict[str, Any]) -> None:
    files: list[dict[str, Any]] = []
    for path in sorted(out.rglob("*")):
        if not path.is_file() or path.name == "manifest.json":
            continue
        relative = path.relative_to(out).as_posix()
        files.append({"path": relative, "bytes": path.stat().st_size,
                      "sha256": sha256_file(path)})
    write_json(out / "manifest.json", {
        "notice": "SYNTHETIC FIXTURE. Every record in this estate is invented.",
        "pack": "government",
        "generator": "generate.py",
        "seed": seed,
        "scale": scale,
        "requested_counts": counts,
        "row_counts": row_counts,
        "totals": {
            "rows": sum(row_counts.values()),
            "files": len(files),
            "bytes": sum(entry["bytes"] for entry in files),
        },
        "entity_resolution": extra,
        "files": files,
    })


def main(argv: Sequence[str] | None = None) -> int:
    parser = argparse.ArgumentParser(
        description="Generate the synthetic government data estate.")
    parser.add_argument("--seed", type=int, default=DEFAULT_SEED,
                        help=f"RNG seed (default {DEFAULT_SEED})")
    parser.add_argument("--scale", type=float, default=1.0,
                        help="multiplier applied to every default count")
    parser.add_argument("--out", type=Path, default=Path(__file__).resolve().parent,
                        help="output directory (defaults to this file's directory)")
    parser.add_argument("--no-clean", action="store_true",
                        help="do not delete previously generated output first")
    args = parser.parse_args(argv)

    if args.scale <= 0:
        parser.error("--scale must be positive")

    out: Path = args.out.resolve()
    out.mkdir(parents=True, exist_ok=True)
    counts = {key: max(int(round(value * args.scale)), 1)
              for key, value in DEFAULT_COUNTS.items()}

    if not args.no_clean:
        clean(out)

    print(f"government estate: seed={args.seed} scale={args.scale} out={out}")

    population = stream(args.seed, "population")
    parcels = build_parcels(population, counts["parcels"])
    persons = build_persons(population, counts["persons"], parcels)
    negatives = build_confusable_pairs(population, persons,
                                       max(int(counts["persons"] * 0.08), 1))

    permits_data = emit_permits(out, args.seed, persons, parcels, counts)
    print(f"  permits_registry   {sum(permits_data['counts'].values()):>8,} rows")
    benefits_data = emit_benefits(out, args.seed, persons, permits_data, counts)
    print(f"  benefits           {sum(benefits_data['counts'].values()):>8,} rows")
    legacy_data = emit_legacy(out, args.seed, persons, counts)
    print(f"  legacy_records     {legacy_data['record_count']:>8,} records")
    gis_data = emit_gis(out, args.seed, parcels)
    print(f"  gis_parcels        {sum(gis_data['counts'].values()):>8,} rows")
    case_file_data = emit_case_files(out, args.seed, permits_data, benefits_data,
                                     counts)
    print(f"  case_files         {counts['documents']:>8,} documents")
    mail_data = emit_correspondence(out, args.seed, permits_data, benefits_data,
                                    counts)
    print(f"  correspondence     {counts['emails']:>8,} messages")
    registry_data = emit_public_registry(out, args.seed, persons, parcels, counts)
    print(f"  public_registry    {sum(registry_data['counts'].values()):>8,} records")
    photo_data = emit_inspection_photos(out, args.seed, permits_data, counts)
    print(f"  inspection_photos  "
          f"{photo_data['counts']['inspection_photos.sidecars']:>8,} sidecars")

    planted = (mail_data["planted"] + case_file_data["planted"]
               + photo_data["planted"]
               + [{"injection_id": note["injection_id"],
                   "location": note["location"],
                   "case_ref": note["claim_id"]}
                  for note in benefits_data["planted_notes"]])
    planted.sort(key=lambda entry: entry["injection_id"])
    write_injection_manifest(out, planted)

    row_counts: dict[str, int] = {}
    for block in (permits_data, benefits_data, legacy_data, gis_data,
                  case_file_data, mail_data, registry_data, photo_data):
        row_counts.update(block["counts"])

    truth = write_ground_truth(out, persons, negatives, row_counts)
    write_manifest(out, args.seed, args.scale, counts, row_counts, {
        "persons": len(persons),
        "appearances": truth["appearances"],
        "negative_pairs": truth["negatives"],
        "injections_planted": len(planted),
    })

    print(f"  ---")
    print(f"  total rows/records {sum(row_counts.values()):>8,}")
    print(f"  people             {len(persons):>8,} "
          f"({truth['appearances']:,} appearances, "
          f"{truth['negatives']} negative pairs)")
    print(f"  injections planted {len(planted):>8,}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
