def build_persons(rnd: Random, count: int, parcels: list[Parcel]) -> list[Person]:
    persons: list[Person] = []
    used_names: set[tuple[str, str]] = set()
    for index in range(count):
        while True:
            surname = (SURNAME_PREFIX[rnd.randrange(len(SURNAME_PREFIX))]
                       + SURNAME_SUFFIX[rnd.randrange(len(SURNAME_SUFFIX))])
            if rnd.random() < 0.06:
                surname += "-" + (SURNAME_PREFIX[rnd.randrange(len(SURNAME_PREFIX))]
                                  + SURNAME_SUFFIX[rnd.randrange(len(SURNAME_SUFFIX))])
            first = GIVEN_NAMES[rnd.randrange(len(GIVEN_NAMES))]
            middle = GIVEN_NAMES[rnd.randrange(len(GIVEN_NAMES))]
            forenames = first if rnd.random() < 0.35 else f"{first} {middle}"
            if (forenames, surname) not in used_names:
                used_names.add((forenames, surname))
                break
        digits_a = f"{rnd.randint(0, 9999):04d}"
        digits_b = f"{rnd.randint(0, 9999):04d}"
        arn = f"AM-{digits_a}-{digits_b}-{check_letter(digits_a + digits_b)}"
        home = parcels[rnd.randrange(len(parcels))]
        address = Address(home.line1, home.locality, home.postcode, home.parcel_id)
        previous = None
        moved_on = None
        if rnd.random() < 0.34:
            old = parcels[rnd.randrange(len(parcels))]
            previous = Address(old.line1, old.locality, old.postcode, old.parcel_id)
            moved_on = rand_date(rnd, date(2012, 1, 1), date(2026, 4, 1))
        former_surname = None
        if rnd.random() < 0.11:
            former_surname = (SURNAME_PREFIX[rnd.randrange(len(SURNAME_PREFIX))]
                              + SURNAME_SUFFIX[rnd.randrange(len(SURNAME_SUFFIX))])
        handle = f"{first.lower()}.{surname.split('-')[0].lower()}{rnd.randint(2, 89)}"
        persons.append(Person(
            gt_id=f"GT-PER-{index + 1:05d}",
            surname=surname,
            forenames=forenames,
            dob=rand_date(rnd, date(1938, 1, 1), date(2007, 12, 31)),
            arn=arn,
            email=f"{handle}@{MAIL_DOMAIN_PUB}",
            phone=f"+99 {rnd.randint(200, 989)} {rnd.randint(100, 999)} "
                  f"{rnd.randint(1000, 9999)}",
            address=address,
            previous_address=previous,
            former_surname=former_surname,
            moved_on=moved_on,
        ))
    return persons


def build_confusable_pairs(rnd: Random, persons: list[Person],
                           pair_count: int) -> list[dict[str, str]]:
    """Force a set of DISTINCT people to look alike.

    These are the negative examples: a resolver that merges any of them is
    wrong, and ../GROUND_TRUTH.md scores that as a false merge.
    """
    negatives: list[dict[str, str]] = []
    candidates = list(range(len(persons)))
    rnd.shuffle(candidates)
    cursor = 0
    for _ in range(pair_count):
        if cursor + 1 >= len(candidates):
            break
        left, right = persons[candidates[cursor]], persons[candidates[cursor + 1]]
        cursor += 2
        style = weighted(rnd, [("same_surname_same_dob", 3),
                               ("same_name_different_dob", 3),
                               ("same_household_same_initials", 2),
                               ("adjacent_resident_number", 2)])
        if style == "same_surname_same_dob":
            right.surname = left.surname
            right.dob = left.dob
            reason = ("same surname and identical date of birth; different "
                      "forenames and different resident numbers")
        elif style == "same_name_different_dob":
            right.surname = left.surname
            right.forenames = left.forenames
            right.dob = date(left.dob.year - rnd.randint(19, 31),
                             left.dob.month, min(left.dob.day, 28))
            reason = ("identical full name, 19-31 years apart -- the classic "
                      "parent/child collision")
        elif style == "same_household_same_initials":
            right.surname = left.surname
            right.address = Address(left.address.line1, left.address.locality,
                                    left.address.postcode, left.address.parcel_id)
            right.forenames = (left.forenames.split()[0][0]
                               + GIVEN_NAMES[rnd.randrange(len(GIVEN_NAMES))][1:])
            reason = ("same surname, same address, same first initial -- "
                      "indistinguishable once a form records an initial only")
        else:
            chars = list(left.arn)
            positions = [i for i, ch in enumerate(chars) if ch.isdigit()]
            index = rnd.choice(positions)
            chars[index] = str((int(chars[index]) + 1) % 10)
            right.arn = "".join(chars)
            reason = ("resident numbers one digit apart -- looks exactly like "
                      "the transposition traps, but these are two people")
        left.traps.append(f"neg.{style}")
        right.traps.append(f"neg.{style}")
        negatives.append({
            "left": left.gt_id, "right": right.gt_id,
            "style": style, "reason": reason,
        })
    return negatives


