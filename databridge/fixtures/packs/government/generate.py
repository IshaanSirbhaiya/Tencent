def _write_loader(seed_dir: Path, label: str) -> None:
    names = sorted(p.name for p in seed_dir.glob("*.sql") if p.name != "load_all.sql")
    body = [BANNER_SQL,
            f"-- Loader for the {label} seed.  Run AFTER ../schema.sql:",
            f"--   psql -v ON_ERROR_STOP=1 -f schema.sql",
            f"--   psql -v ON_ERROR_STOP=1 -f seed/load_all.sql",
            "-- \\ir resolves relative to THIS file, so the loader works from any cwd.",
            ""]
    body += [f"\\ir {name}" for name in names]
    body.append("")
    write_text(seed_dir / "load_all.sql", "\n".join(body))


