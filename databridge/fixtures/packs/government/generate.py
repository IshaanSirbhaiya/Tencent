def write_ground_truth(out: Path, persons: list[Person],
                       negatives: list[dict[str, str]],
                       counts_by_source: dict[str, int]) -> dict[str, Any]:
    appearance_rows: list[list[Any]] = []
    for person in persons:
        for appearance in person.appearances:
            appearance_rows.append([
                person.gt_id, appearance["source"], appearance["local_key"],
                appearance["name_as_recorded"], appearance["id_as_recorded"],
                ";".join(appearance["traps"]),
            ])
    write_csv(out / "entity_resolution_truth.csv",
              ["gt_person_id", "source", "local_key", "name_as_recorded",
               "id_as_recorded", "traps"], appearance_rows)

    write_csv(out / "entity_resolution_negatives.csv",
              ["left_gt_person_id", "right_gt_person_id", "confusion_style",
               "why_it_is_hard"],
              [[n["left"], n["right"], n["style"], n["reason"]] for n in negatives])

    trap_counts: dict[str, int] = {}
    for person in persons:
        for trap in person.traps:
            trap_counts[trap] = trap_counts.get(trap, 0) + 1

    source_spread: dict[int, int] = {}
    for person in persons:
        distinct = len({a["source"].split(".")[0] for a in person.appearances})
        source_spread[distinct] = source_spread.get(distinct, 0) + 1

    lines = [
        "# GROUND_TRUTH -- the answer key for entity resolution",
        "",
        "> **SYNTHETIC FIXTURE.** Every person named in this file is invented.",
        "> Generated by `generate.py`; regenerate with the same seed and this file",
        "> comes back byte-identical.",
        "",
        "This estate scatters the same human beings across eight sources that never",
        "agreed on an identifier, a name format, or an address. That is not an",
        "accident of generation -- it is the point. This file says who is really",
        "who, so a resolver can be **scored** rather than admired.",
        "",
        "## The files",
        "",
        "| File | What it is |",
        "|---|---|",
        "| `entity_resolution_truth.csv` | the complete mapping: one row per "
        "appearance of a person in a source, with the name and identifier exactly "
        "as that source records them, and the traps applied |",
        "| `entity_resolution_negatives.csv` | pairs of **different** people who "
        "look alike on purpose; merging any of them is a false merge |",
        "| this file | the summary, the statistics, and worked examples |",
        "",
        "## How to score against it",
        "",
        "1. Run resolution over the estate and emit clusters of source records.",
        "2. Join each record back to `gt_person_id` via "
        "`(source, local_key)` in `entity_resolution_truth.csv`.",
        "3. Report **pairwise precision / recall / F1** over the within-cluster",
        "   pairs, and report false merges separately -- a false merge of two",
        "   citizens is not the same kind of error as a missed link, and averaging",
        "   them hides the one that matters.",
        "4. Every pair in `entity_resolution_negatives.csv` that ends up in one",
        "   cluster is a **hard failure**, not a rounding error.",
        "",
        "**A resolver that scores 100% here is misconfigured.** Several of these",
        "identities are genuinely undecidable from the data alone -- an initial, a",
        "truncated surname and no identifier is not enough, and the correct output",
        "is a candidate set for a human, never a merge. That is the constraint the",
        "whole system is built around: the system presents candidates; a named human",
        "attests; `requires_human_selection` stays `Literal[True]`.",
        "",
        "## Population",
        "",
        f"* **{len(persons):,} distinct people**, {len(appearance_rows):,} total "
        "appearances across the estate.",
        f"* **{len(negatives)} planted negative pairs** (distinct people built to "
        "look alike).",
        "",
        "| Distinct sources a person appears in | People |",
        "|---:|---:|",
    ]
    for distinct in sorted(source_spread):
        lines.append(f"| {distinct} | {source_spread[distinct]:,} |")

    lines += [
        "",
        "| Source | Records emitted |",
        "|---|---:|",
    ]
    for name, value in counts_by_source.items():
        lines.append(f"| `{name}` | {value:,} |")

    lines += [
        "",
        "## The traps, and how often each is planted",
        "",
        "| Trap | What it does | Instances |",
        "|---|---|---:|",
    ]
    for trap in sorted(trap_counts, key=lambda t: (-trap_counts[t], t)):
        lines.append(f"| `{trap}` | {TRAP_GLOSSARY.get(trap, 'see generate.py')} "
                     f"| {trap_counts[trap]:,} |")

    lines += [
        "",
        "## Worked examples",
        "",
        "The first forty clusters in full. The rest are in the CSV.",
        "",
    ]
    for person in persons[:40]:
        lines += [
            f"### {person.gt_id} -- {person.full_name}",
            "",
            f"Truth: born {person.dob.isoformat()}, resident number "
            f"`{person.arn}`, at {person.address.line1}, {person.address.locality} "
            f"{person.address.postcode}."
            + (f" Formerly known as {person.former_surname}."
               if person.former_surname else ""),
            "",
            "| Source | Local key | Name as recorded | Id as recorded | Traps |",
            "|---|---|---|---|---|",
        ]
        for appearance in person.appearances:
            lines.append(
                f"| `{appearance['source']}` | `{appearance['local_key']}` "
                f"| {appearance['name_as_recorded']} "
                f"| `{appearance['id_as_recorded'] or '--'}` "
                f"| {', '.join(appearance['traps']) or '--'} |")
        lines.append("")

    lines += [
        "## Full roster",
        "",
        "One row per person. Detail is in `entity_resolution_truth.csv`.",
        "",
        "| Person | Name | Born | Resident number | Appearances | Sources |",
        "|---|---|---|---|---:|---|",
    ]
    for person in persons:
        sources = sorted({a["source"].split(".")[0] for a in person.appearances})
        lines.append(
            f"| `{person.gt_id}` | {person.full_name} | {person.dob.isoformat()} "
            f"| `{person.arn}` | {len(person.appearances)} "
            f"| {', '.join(sources) or '--'} |")

    lines += [
        "",
        "## Negative pairs -- do not merge these",
        "",
        "| Left | Right | Style | Why it is hard |",
        "|---|---|---|---|",
    ]
    for negative in negatives:
        lines.append(f"| `{negative['left']}` | `{negative['right']}` "
                     f"| `{negative['style']}` | {negative['reason']} |")
    lines.append("")

    write_text(out / "GROUND_TRUTH.md", "\n".join(lines))
    return {"appearances": len(appearance_rows), "negatives": len(negatives),
            "trap_counts": trap_counts}


