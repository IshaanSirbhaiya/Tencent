def stream(seed: int, name: str) -> Random:
    """A named, reproducible RNG stream.

    zlib.crc32 rather than hash(): Python string hashing is salted per process,
    which would silently destroy reproducibility.
    """
    return Random(seed ^ zlib.crc32(name.encode("utf-8")))


def sql_lit(value: Any) -> str:
    if value is None:
        return "NULL"
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, (int, float)):
        return repr(value) if isinstance(value, float) else str(value)
    if isinstance(value, datetime):
        return "'" + value.strftime("%Y-%m-%d %H:%M:%S+00") + "'"
    if isinstance(value, date):
        return "'" + value.isoformat() + "'"
    return "'" + str(value).replace("'", "''") + "'"


def rand_date(rnd: Random, start: date, end: date) -> date:
    span = (end - start).days
    return start + timedelta(days=rnd.randint(0, max(span, 0)))


def rand_dt(rnd: Random, day: date, hour_lo: int = 8, hour_hi: int = 18) -> datetime:
    return datetime(day.year, day.month, day.day,
                    rnd.randint(hour_lo, hour_hi), rnd.randint(0, 59),
                    rnd.randint(0, 59), tzinfo=TZ)


def weighted(rnd: Random, pairs: Sequence[tuple[Any, int]]) -> Any:
    total = sum(w for _v, w in pairs)
    pick = rnd.randint(1, total)
    for value, weight in pairs:
        pick -= weight
        if pick <= 0:
            return value
    return pairs[-1][0]


def check_letter(digits: str) -> str:
    """Deterministic pseudo-check character for invented identifiers."""
    return "ABCDEFGHJKLMNPRSTVWXYZ"[sum(int(d) for d in digits if d.isdigit()) % 22]


def fixed(value: str | None, width: int) -> str:
    """Truncate-or-pad to a fixed width, the way a COBOL MOVE does."""
    text = "" if value is None else str(value).upper()
    return text[:width].ljust(width)


def num_fixed(value: int | None, width: int) -> str:
    if value is None:
        return "0" * width
    return str(abs(int(value)))[-width:].rjust(width, "0")


def cymd(value: date | None) -> str:
    return "00000000" if value is None else value.strftime("%Y%m%d")


def sha256_file(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as handle:
        for chunk in iter(lambda: handle.read(65536), b""):
            digest.update(chunk)
    return digest.hexdigest()


def write_text(path: Path, text: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    # newline="\n" everywhere: byte-identical output on Windows and POSIX.
    with path.open("w", encoding="utf-8", newline="\n") as handle:
        handle.write(text)


def write_json(path: Path, payload: Any) -> None:
    write_text(path, json.dumps(payload, indent=2, sort_keys=False) + "\n")


def write_csv(path: Path, header: Sequence[str], rows: Iterable[Sequence[Any]]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("w", encoding="utf-8", newline="") as handle:
        writer = csv.writer(handle, lineterminator="\n")
        writer.writerow(header)
        writer.writerows(rows)


def write_inserts(directory: Path, stem: str, table: str, columns: Sequence[str],
                  rows: Sequence[Sequence[Any]], note: str = "") -> list[str]:
    """Emit one or more .sql shards of INSERT statements.  Returns file names."""
    directory.mkdir(parents=True, exist_ok=True)
    written: list[str] = []
    shards = [rows[i:i + SQL_SHARD_ROWS] for i in range(0, len(rows), SQL_SHARD_ROWS)] or [[]]
    multi = len(shards) > 1
    for index, shard in enumerate(shards, start=1):
        name = f"{stem}_part{index:03d}.sql" if multi else f"{stem}.sql"
        parts = [BANNER_SQL, f"-- {table}: {len(shard)} rows"]
        if note:
            parts.append(f"-- {note}")
        parts.append("")
        collist = ", ".join(columns)
        for start in range(0, len(shard), SQL_BATCH_ROWS):
            batch = shard[start:start + SQL_BATCH_ROWS]
            values = ",\n".join(
                "  (" + ", ".join(sql_lit(cell) for cell in row) + ")" for row in batch
            )
            parts.append(f"INSERT INTO {table} ({collist}) VALUES\n{values};\n")
        write_text(directory / name, "\n".join(parts))
        written.append(name)
    return written


