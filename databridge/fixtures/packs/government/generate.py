def name_variant(person: Person, rnd: Random,
                 kinds: Sequence[str]) -> tuple[str, str, list[str]]:
    """Return (forenames, surname, traps) after applying the named distortions."""
    forenames, surname, traps = person.forenames, person.surname, []
    for kind in kinds:
        if kind == "initial_only":
            forenames = forenames.split()[0][0] + "."
            traps.append("name.initial_only")
        elif kind == "middle_dropped" and len(forenames.split()) > 1:
            forenames = forenames.split()[0]
            traps.append("name.middle_dropped")
        elif kind == "order_swapped":
            forenames, surname = surname, forenames.split()[0]
            traps.append("name.order_swapped")
        elif kind == "former_surname" and person.former_surname:
            surname = person.former_surname
            traps.append("name.former_surname")
        elif kind == "typo" and len(surname) > 3:
            index = rnd.randrange(1, len(surname) - 1)
            surname = surname[:index] + surname[index + 1:]
            traps.append("name.typo")
        elif kind == "transposed_letters" and len(surname) > 4:
            index = rnd.randrange(1, len(surname) - 2)
            surname = (surname[:index] + surname[index + 1] + surname[index]
                       + surname[index + 2:])
            traps.append("name.transposed_letters")
        elif kind == "hyphen_dropped" and "-" in surname:
            surname = surname.replace("-", " ")
            traps.append("name.hyphen_dropped")
        elif kind == "uppercase":
            forenames, surname = forenames.upper(), surname.upper()
            traps.append("name.uppercase")
        elif kind == "truncated_30":
            clipped = surname[:30]
            if clipped != surname:
                traps.append("name.truncated_30")
            surname = clipped
    return forenames, surname, traps


def id_variant(arn: str, rnd: Random, kind: str) -> tuple[str | None, list[str]]:
    if kind == "exact":
        return arn, []
    if kind == "absent":
        return None, ["id.absent"]
    if kind == "format_stripped":
        return arn.replace("-", ""), ["id.format_stripped"]
    if kind == "digit_transposed":
        chars = list(arn)
        positions = [i for i, ch in enumerate(chars) if ch.isdigit()]
        index = rnd.randrange(0, len(positions) - 1)
        a, b = positions[index], positions[index + 1]
        if chars[a] == chars[b]:
            chars[a] = str((int(chars[a]) + 1) % 10)
        chars[a], chars[b] = chars[b], chars[a]
        return "".join(chars), ["id.digit_transposed"]
    if kind == "digit_dropped":
        chars = list(arn)
        positions = [i for i, ch in enumerate(chars) if ch.isdigit()]
        del chars[rnd.choice(positions)]
        return "".join(chars), ["id.digit_dropped"]
    if kind == "ocr_confusion":
        chars = list(arn)
        positions = [i for i, ch in enumerate(chars) if ch.isdigit()]
        index = rnd.choice(positions)
        chars[index] = {"0": "O", "1": "l", "5": "S", "8": "B", "6": "G",
                        "2": "Z", "9": "g"}.get(chars[index], "O")
        return "".join(chars), ["id.ocr_confusion"]
    if kind == "checkletter_dropped":
        return arn.rsplit("-", 1)[0], ["id.checkletter_dropped"]
    return arn, []


def address_variant(address: Address, rnd: Random,
                    kind: str) -> tuple[Address, list[str]]:
    line1, locality, postcode = address.line1, address.locality, address.postcode
    traps: list[str] = []
    if kind == "abbreviated":
        for full, short in STREET_ABBREV.items():
            if line1.endswith(full):
                line1 = line1[: -len(full)] + short
                traps.append("addr.abbreviated")
                break
    elif kind == "unit_prefixed":
        line1 = f"Flat {rnd.randint(1, 12)}, {line1}"
        traps.append("addr.unit_prefixed")
    elif kind == "postcode_typo":
        chars = list(postcode)
        positions = [i for i, ch in enumerate(chars) if ch.isdigit()]
        if positions:
            index = rnd.choice(positions)
            chars[index] = str((int(chars[index]) + 1) % 10)
        postcode = "".join(chars)
        traps.append("addr.postcode_typo")
    elif kind == "locality_dropped":
        locality = ""
        traps.append("addr.locality_dropped")
    return Address(line1, locality, postcode, address.parcel_id), traps


def ocr_noise(text: str, rnd: Random, rate: float = 0.018) -> str:
    """Character-level scanner damage.  Deterministic given the RNG stream."""
    out: list[str] = []
    index = 0
    while index < len(text):
        applied = False
        if text[index].isalnum() and rnd.random() < rate:
            for source, target in OCR_CONFUSIONS:
                if text.startswith(source, index) and rnd.random() < 0.5:
                    out.append(target)
                    index += len(source)
                    applied = True
                    break
        if not applied:
            out.append(text[index])
            index += 1
    return "".join(out)


def scanner_wrap(text: str, rnd: Random, width: int = 72) -> str:
    """Break lines the way a scan-to-text pass does: hard wraps mid-word,
    stray hyphenation, and the occasional doubled space."""
    words = text.split()
    lines: list[str] = []
    current = ""
    for word in words:
        if len(current) + len(word) + 1 > width:
            if len(word) > 7 and rnd.random() < 0.28:
                cut = rnd.randint(3, len(word) - 3)
                lines.append((current + " " + word[:cut] + "-").strip())
                current = word[cut:]
            else:
                lines.append(current.strip())
                current = word
        else:
            current = f"{current} {word}" if current else word
        if rnd.random() < 0.05:
            current += " "
    if current.strip():
        lines.append(current.strip())
    return "\n".join(lines)


