    inspection_rows: list[list[Any]] = []
    inspections: list[dict[str, Any]] = []
    inspection_index = 0
    for application in applications:
        if not application["requires_inspection"]:
            continue
        for _ in range(weighted(rnd, [(0, 2), (1, 5), (2, 3), (3, 1)])):
            inspection_index += 1
            scheduled_day = application["submitted"].date() + timedelta(
                days=rnd.randint(5, 400))
            if scheduled_day > TODAY:
                continue
            performed = scheduled_day + timedelta(days=rnd.choice([0, 0, 0, 1, 3, 7]))
            done = performed <= TODAY and rnd.random() < 0.9
