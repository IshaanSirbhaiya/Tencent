'use client';
import { FlaskConical, History, ShieldCheck } from 'lucide-react';
import { Badge, Card, CodeHash, SkeletonText } from '@/components/ui';
import { fmtDate } from '@/lib/format';
import type { EvalSummary } from '@/lib/types';
import { MiniTable, SourceChip } from './ChartCard';
import { int, rate } from './format';

function Fig({ label, value, sub, testId }: { label: string; value: React.ReactNode; sub?: React.ReactNode; testId?: string }) {
  return (
    <div className="min-w-0 rounded-md border border-line bg-bg/40 px-3 py-2.5" data-testid={testId}>
      <p className="text-caption text-muted">{label}</p>
      <p className="mt-0.5 text-heading tabular-nums text-fg">{value}</p>
      {sub ? <p className="mt-0.5 text-caption tabular-nums text-subtle">{sub}</p> : null}
    </div>
  );
}

const pctOrDash = (v: number | undefined, dp = 2) => (typeof v === 'number' ? rate(v, dp) : '—');

/**
 * The offline evaluation, from /eval_summary.json (generated by scripts/eval_summary.py). Kept apart
 * from live ledger numbers: different source, different chip, never on the same axis.
 */
export function EvalPanel({ data, error, compact }: { data: EvalSummary | null; error?: boolean; compact?: boolean }) {
  return (
    <Card className="min-w-0" aria-labelledby="eval-title" data-testid="eval-panel">
      <div className="flex flex-wrap items-start justify-between gap-2 border-b border-line px-4 py-3">
        <div className="min-w-0">
          <h2 id="eval-title" className="flex items-center gap-2 text-heading-sm text-fg">
            <FlaskConical aria-hidden className="h-4 w-4 text-muted" /> Evaluation
          </h2>
          <p className="mt-0.5 text-caption text-muted">Proven offline at scale, not live traffic. Leak = a restricted passage reaching a model or an answer.</p>
        </div>
        <div className="flex flex-wrap items-center gap-2">
          {data?.stale ? (
            <Badge tone="warn" icon={History} data-testid="eval-rerun-pending">
              Re-run pending
            </Badge>
          ) : null}
          <SourceChip>eval · {data?.run_date ? fmtDate(data.run_date) : '—'}</SourceChip>
        </div>
      </div>
      <div className="px-4 py-3">
        {error ? <p className="text-body-sm text-muted">The evaluation summary is not available in this build.</p> : null}
        {!data && !error ? <SkeletonText lines={4} label="Loading the evaluation summary" /> : null}
        {data ? (
          <>
            {data.stale && data.note ? <p className="mb-3 rounded-md border border-warn/40 bg-warn/10 px-3 py-2 text-caption text-fg">{data.note}</p> : null}
            <div className={compact ? 'grid grid-cols-2 gap-2' : 'grid grid-cols-2 gap-2 lg:grid-cols-4'}>
              <Fig
                label="Leaks"
                testId="eval-leaks"
                value={
                  <span className="inline-flex items-center gap-1.5">
                    {int(data.leaks)} <span className="text-body-sm font-normal text-muted">/ {int(data.requests)}</span>
                  </span>
                }
                sub={`95% upper bound ${pctOrDash(data.upper95)} per request`}
              />
              <Fig
                label="Restricted ≡ absent"
                value={
                  <span>
                    {int(data.differential?.mismatches)} <span className="text-body-sm font-normal text-muted">/ {int(data.differential?.pairs)} pairs</span>
                  </span>
                }
                sub={`control mismatches ${int(data.differential?.control_mismatches)}`}
              />
              <Fig
                label="Prompt injection"
                value={
                  <span>
                    {int(data.injection?.hard_failures)} <span className="text-body-sm font-normal text-muted">/ {int(data.injection?.requests)}</span>
                  </span>
                }
                sub="hard failures"
              />
              <Fig
                label="Cited recall"
                value={
                  data.cited_recall?.range ? (
                    <span>
                      {pctOrDash(data.cited_recall.range.min, 1)}–{pctOrDash(data.cited_recall.range.max, 1)}
                    </span>
                  ) : (
                    '—'
                  )
                }
                sub={data.recall?.released_all_modes ? `released recall ${pctOrDash(data.recall.released_all_modes.min, 0)}` : undefined}
              />
            </div>
            {!compact ? (
              <div className="mt-3 grid gap-3 lg:grid-cols-2">
                <MiniTable
                  caption="Evaluation per answer mode"
                  head={['Mode', 'Requests', 'With leak', '95% upper bound', 'Refused']}
                  rows={Object.entries(data.per_mode ?? {}).map(([k, v]) => [
                    <span key={k} className="font-mono text-caption">
                      {k}
                    </span>,
                    int(v.requests),
                    int(v.with_leak),
                    pctOrDash(v.upper95),
                    int(v.refused),
                  ])}
                />
                <dl className="grid grid-cols-2 gap-x-4 gap-y-2 self-start text-body-sm">
                  <div>
                    <dt className="text-micro uppercase tracking-wide text-subtle">Model payloads</dt>
                    <dd className="tabular-nums text-fg">
                      {int(data.payload_requests)} · bound {pctOrDash(data.payload_upper95)}
                    </dd>
                  </div>
                  <div>
                    <dt className="text-micro uppercase tracking-wide text-subtle">Policy violations</dt>
                    <dd className="tabular-nums text-fg">{int(data.violations)}</dd>
                  </div>
                  <div>
                    <dt className="text-micro uppercase tracking-wide text-subtle">Tests</dt>
                    <dd className="tabular-nums text-fg">
                      {int(data.tests?.backend)} backend · {int(data.tests?.e2e)} e2e
                    </dd>
                  </div>
                  <div>
                    <dt className="text-micro uppercase tracking-wide text-subtle">Canaries</dt>
                    <dd className="inline-flex items-center gap-1 text-fg">
                      {data.canaries_valid ? <ShieldCheck aria-hidden className="h-3.5 w-3.5 text-ok" /> : null}
                      {data.canaries_valid === undefined ? '—' : data.canaries_valid ? 'valid' : 'invalid'}
                    </dd>
                  </div>
                  <div className="col-span-2">
                    <dt className="text-micro uppercase tracking-wide text-subtle">Run</dt>
                    <dd className="flex flex-wrap items-center gap-2 text-fg">
                      <span className="tabular-nums">{data.run_date ? fmtDate(data.run_date) : '—'}</span>
                      {data.full_run ? <span className="text-subtle">full run</span> : null}
                      <CodeHash value={data.git_sha} head={8} tail={4} label="git sha" />
                    </dd>
                  </div>
                  {data.smoke?.run_date ? (
                    <div className="col-span-2">
                      <dt className="text-micro uppercase tracking-wide text-subtle">Later smoke run</dt>
                      <dd className="tabular-nums text-fg">
                        {fmtDate(data.smoke.run_date)} · {int(data.smoke.leaks)} leaks / {int(data.smoke.requests)}
                      </dd>
                    </div>
                  ) : null}
                </dl>
              </div>
            ) : null}
          </>
        ) : null}
      </div>
    </Card>
  );
}
